// ponytail: one-off data merge script, run manually when source manifests change (not part of build pipeline)
import { readFileSync, writeFileSync, existsSync } from "fs";

const images = JSON.parse(readFileSync("public/images/manifest.json", "utf-8"));
const voiceover = JSON.parse(readFileSync("voiceover.json", "utf-8"));
const sfxCues = JSON.parse(readFileSync("public/audio/sfx/sfx-cues.json", "utf-8"));

const textById = Object.fromEntries(voiceover.map((v) => [v.id, v.text]));

const KEYWORDS = [
  "Wyoming", "Colorado", "Mississippi", "Virginia", "Carolina", "Bắc", "Nam",
  "Charles", "Đệ", "Nhị", "John", "Smith", "Ohio", "Michigan", "Maumee",
  "Toledo", "Washington", "Cách", "mạng", "Quốc", "hội",
];

const MOTION_MAP = {
  "static hold": "static",
  "slow zoom-in": "zoom-in",
  "pan left-to-right": "pan-lr",
  "pan down-to-up": "pan-du",
  "fade-scale": "fade-scale",
  "slide-up": "slide-up",
};

function splitChunks(text) {
  const words = text.trim().split(/\s+/);
  const chunks = [];
  for (let i = 0; i < words.length; i += 2) {
    const chunk = words.slice(i, i + 2);
    chunks.push({
      words: chunk.map((w) => ({
        text: w,
        keyword: KEYWORDS.some((k) => w.replace(/[.,?:]/g, "") === k),
      })),
    });
  }
  return chunks;
}

const beats = images
  .sort((a, b) => a.startFrame - b.startFrame)
  .map((img) => {
    const text = textById[img.beatId];
    const bgPath = `public/images/layers/scene-${img.beatId}-bg.png`;
    const fgPath = `public/images/layers/scene-${img.beatId}-fg.png`;
    const hasLayers = existsSync(bgPath) && existsSync(fgPath);
    return {
      id: img.beatId,
      asset: img.asset.replace(/^public\//, ""),
      bgAsset: hasLayers ? bgPath.replace(/^public\//, "") : undefined,
      fgAsset: hasLayers ? fgPath.replace(/^public\//, "") : undefined,
      motion: MOTION_MAP[img.motion] ?? "static",
      startFrame: img.startFrame,
      durationFrames: img.durationFrames,
      text,
      chunks: splitChunks(text),
    };
  });

const totalFrames = beats.reduce((sum, b) => sum + b.durationFrames, 0);

writeFileSync(
  "src/data/beats.ts",
  `// Generated by scripts/build-beats-data.mjs from public/images/manifest.json + voiceover.json. Do not hand-edit; rerun the script instead.
export interface BeatWord {
  text: string;
  keyword: boolean;
}
export interface BeatChunk {
  words: BeatWord[];
}
export interface Beat {
  id: string;
  asset: string;
  bgAsset?: string;
  fgAsset?: string;
  motion: "static" | "zoom-in" | "pan-lr" | "pan-du" | "fade-scale" | "slide-up";
  startFrame: number;
  durationFrames: number;
  text: string;
  chunks: BeatChunk[];
}

export const TOTAL_FRAMES = ${totalFrames};

export const beats: Beat[] = ${JSON.stringify(beats, null, 2)};
`
);

writeFileSync(
  "src/data/sfxCues.ts",
  `// Generated by scripts/build-beats-data.mjs from public/audio/sfx/sfx-cues.json. Do not hand-edit; rerun the script instead.
export interface SfxCue {
  beatId: string;
  type: string;
  file: string;
  frame: number;
  volume: number;
  durationFrames?: number;
  note?: string;
}

export const sfxCues: SfxCue[] = ${JSON.stringify(
    sfxCues.map((c) => ({ ...c, file: c.file.replace(/^public\//, "") })),
    null,
    2
  )};
`
);

console.log(`beats: ${beats.length}, totalFrames: ${totalFrames}`);
